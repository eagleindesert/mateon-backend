--
-- 이름이 겹치는 기존 두 가지와 다른 값이다.
--   * user_portfolios (V25): PDF 를 올리면 AI 가 만들어 주는 요약. 1:N 이고 사람이 쓰는 값이 아니다.
--   * team_applications.portfolio_url: 팀 지원서에 첨부하는 링크. 지원서 단위 값이지 프로필 값이 아니다.
