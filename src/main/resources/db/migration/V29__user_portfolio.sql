-- 한 줄 소개인 tagline(varchar 200) 으로는 담기지 않아 따로 둔다.
--
-- 길이 제한을 두지 않는 이유: 몇 자가 적당한지는 화면 사정이라 바뀌기 쉬운데, varchar(N) 으로
-- 박아 두면 그때마다 마이그레이션이 필요하다. 상한은 UserUpdateRequest 의 @Size 로 잡는다 —
-- 거기 숫자는 요청 본문 상한일 뿐이라 마이그레이션 없이 조정된다.
